/**
 * SeededRandom — the only source of randomness permitted in the authoritative simulation.
 *
 * Algorithm: sfc32 (Small Fast Counter), seeded through a string hash (cyrb128).
 * The full internal state is four uint32 words, which is serialised into the game
 * state so that a saved game resumes the exact same random stream.
 */

export type RandomState = readonly [number, number, number, number];

/** cyrb128 string hash → four 32-bit seeds. Stable across platforms. */
export function hashStringToSeed(input: string): RandomState {
  let h1 = 1779033703;
  let h2 = 3144134277;
  let h3 = 1013904242;
  let h4 = 2773480762;
  for (let i = 0; i < input.length; i++) {
    const k = input.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067);
    h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213);
    h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
  h1 ^= h2 ^ h3 ^ h4;
  h2 ^= h1;
  h3 ^= h1;
  h4 ^= h1;
  return [h1 >>> 0, h2 >>> 0, h3 >>> 0, h4 >>> 0];
}

export class SeededRandom {
  private a: number;
  private b: number;
  private c: number;
  private d: number;

  constructor(seedOrState: string | RandomState) {
    const s = typeof seedOrState === "string" ? hashStringToSeed(seedOrState) : seedOrState;
    this.a = s[0] >>> 0;
    this.b = s[1] >>> 0;
    this.c = s[2] >>> 0;
    this.d = s[3] >>> 0;
    if (typeof seedOrState === "string") {
      // Warm up so that similar seeds diverge quickly.
      for (let i = 0; i < 15; i++) this.nextUint32();
    }
  }

  /** Derive an independent stream (e.g. per subsystem) without consuming this stream. */
  static derive(seed: string, label: string): SeededRandom {
    return new SeededRandom(`${seed}::${label}`);
  }

  getState(): RandomState {
    return [this.a, this.b, this.c, this.d];
  }

  nextUint32(): number {
    this.a >>>= 0;
    this.b >>>= 0;
    this.c >>>= 0;
    this.d >>>= 0;
    let t = (this.a + this.b) | 0;
    this.a = this.b ^ (this.b >>> 9);
    this.b = (this.c + (this.c << 3)) | 0;
    this.c = (this.c << 21) | (this.c >>> 11);
    this.d = (this.d + 1) | 0;
    t = (t + this.d) | 0;
    this.c = (this.c + t) | 0;
    return t >>> 0;
  }

  /** Float in [0, 1). */
  next(): number {
    return this.nextUint32() / 4294967296;
  }

  /** Integer in [min, max] inclusive. */
  int(min: number, max: number): number {
    if (max < min) throw new RangeError(`int(${min}, ${max}): max < min`);
    return min + Math.floor(this.next() * (max - min + 1));
  }

  /** Float in [min, max). */
  range(min: number, max: number): number {
    return min + this.next() * (max - min);
  }

  chance(probability: number): boolean {
    return this.next() < probability;
  }

  pick<T>(items: readonly T[]): T {
    if (items.length === 0) throw new RangeError("pick() on empty array");
    return items[Math.floor(this.next() * items.length)] as T;
  }

  /** Weighted pick; weights must be non-negative and not all zero. */
  weighted<T>(items: readonly T[], weights: readonly number[]): T {
    let total = 0;
    for (const w of weights) total += Math.max(0, w);
    if (total <= 0 || items.length === 0) throw new RangeError("weighted() needs positive weights");
    let roll = this.next() * total;
    for (let i = 0; i < items.length; i++) {
      roll -= Math.max(0, weights[i] ?? 0);
      if (roll < 0) return items[i] as T;
    }
    return items[items.length - 1] as T;
  }

  shuffle<T>(items: readonly T[]): T[] {
    const out = items.slice();
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(this.next() * (i + 1));
      const tmp = out[i] as T;
      out[i] = out[j] as T;
      out[j] = tmp;
    }
    return out;
  }
}
